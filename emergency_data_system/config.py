"""
================================================================================
  系统全局配置文件
================================================================================
  本文件定义了应急数据清洗与可视化系统的所有可配置参数。
  所有模块（data_cleaner / app / database / report / auth）均从此文件
  读取配置，实现单一配置源（Single Source of Truth）。

  配置分类:
    1. 路径配置   —— 上传/输出/日志目录
    2. 上传配置   —— 允许的文件格式与大小限制
    3. 清洗规则   —— 字段映射、必填校验、去重维度、填充策略
    4. 地域配置   —— 地址自适应补全的前缀参数

  使用方式:
    from config import UPLOAD_FOLDER, COLUMN_STANDARD_MAP, FILL_VALUE
    # 直接使用，无需实例化

  自定义指南:
    1. 修改 REGION_PREFIX 以适配不同辖区的地域前缀
    2. 修改 COLUMN_STANDARD_MAP 以适配不同上报模板的字段命名习惯
    3. 修改 FILL_VALUE 以自定义缺失字段的占位文字
    4. 修改 MAX_FILE_SIZE 以调整上传文件大小上限
================================================================================
"""

import os

# ======================================================================
#  1. 路径配置
# ======================================================================
#  所有路径均为相对于项目根目录的绝对路径，确保在任何工作目录下
#  运行 app.py 时都能正确找到对应目录。
# ======================================================================

# 项目根目录（本文件所在目录）
BASE_DIR: str = os.path.dirname(os.path.abspath(__file__))

# 上传文件存储目录 —— 用户上传的原始 Excel 文件暂存于此
UPLOAD_FOLDER: str = os.path.join(BASE_DIR, 'uploads')

# 清洗结果输出目录 —— 清洗后的标准化 Excel 报表存放于此
OUTPUT_FOLDER: str = os.path.join(BASE_DIR, 'outputs')

# 异常日志目录 —— 每次清洗生成的异常数据日志存放于此
LOG_FOLDER: str = os.path.join(BASE_DIR, 'logs')

# 在模块导入时自动创建缺失的目录（幂等操作：已存在则跳过）
# 这确保了首次部署时无需手动创建目录结构
for folder in [UPLOAD_FOLDER, OUTPUT_FOLDER, LOG_FOLDER]:
    os.makedirs(folder, exist_ok=True)

# ======================================================================
#  2. 上传配置
# ======================================================================

# 允许上传的文件扩展名集合（白名单）
# 当前仅支持 .xlsx 格式（OpenXML 标准），.xls 因 xlrd 兼容性问题已移除
# 如需恢复 .xls 支持，需安装 xlrd==1.2.0 并添加 'xls' 到此集合
ALLOWED_EXTENSIONS: set = {'xlsx'}

# 上传文件大小上限：10 MB
# 基层应急报表通常为数百至数千行，10MB 足以覆盖绝大部分场景
# 如遇超大文件，建议先在 Excel 中拆分后再上传
MAX_FILE_SIZE: int = 10 * 1024 * 1024  # 10MB in bytes

# ======================================================================
#  3. 清洗规则配置
# ======================================================================

# --------------------------------------------------------------------
#  3.1 字段列名标准化映射
# --------------------------------------------------------------------
#  键（key）：基层上报 Excel 中可能出现的原始列名
#  值（value）：系统内部统一使用的标准列名
#
#  设计原则：
#    - 覆盖基层最常见的 4 类字段的 20+ 种命名变体
#    - 新增映射只需添加一行，无需修改清洗逻辑代码
#    - 未匹配的列名保持原样，不会被误修改
#
#  示例：
#    原始 Excel 列：["企业", "手机", "日期", "地址"]
#    标准化后：      ["企业名称", "联系电话", "排查日期", "企业地址"]
# --------------------------------------------------------------------
COLUMN_STANDARD_MAP: dict = {
    # ---------- 企业名称（6种常见变体） ----------
    '企业':     '企业名称',
    '公司':     '企业名称',
    '单位':     '企业名称',
    '企业名':   '企业名称',
    '公司名称': '企业名称',
    '单位名称': '企业名称',

    # ---------- 联系电话（7种常见变体） ----------
    '手机':     '联系电话',
    '电话':     '联系电话',
    '手机号':   '联系电话',
    '手机号码': '联系电话',
    '电话号码': '联系电话',
    '联系手机': '联系电话',
    '联系号码': '联系电话',

    # ---------- 企业地址（5种常见变体） ----------
    '地址':     '企业地址',
    '所在地':   '企业地址',
    '公司地址': '企业地址',
    '单位地址': '企业地址',
    '详细地址': '企业地址',

    # ---------- 排查日期（5种常见变体） ----------
    '日期':     '排查日期',
    '排查时间': '排查日期',
    '检查日期': '排查日期',
    '上报日期': '排查日期',
    '录入日期': '排查日期',

    # ---------- 隐患排查（3种常见变体） ----------
    '隐患':     '隐患等级',
    '风险等级': '隐患等级',
    '隐患级别': '隐患等级',
    '风险级别': '隐患等级',
}

# --------------------------------------------------------------------
#  3.2 必填字段列表
# --------------------------------------------------------------------
#  列表中的字段如果为空（或填充值为 FILL_VALUE），将被标记为异常并
#  写入异常日志。这三个字段是应急管理数据台账的核心标识维度：
#    - 企业名称：主体标识，不可缺失
#    - 联系电话：联系方式，用于数据复核
#    - 排查日期：时间维度，用于统计分析和台账归档
# --------------------------------------------------------------------
REQUIRED_FIELDS: list = ['企业名称', '联系电话', '排查日期']

# --------------------------------------------------------------------
#  3.3 去重维度
# --------------------------------------------------------------------
#  当且仅当列表中的所有字段值完全相同时，视为重复数据
#  默认维度：企业名称 + 排查日期
#  逻辑：同一企业在同一天只保留一条排查记录，避免乡镇月报与科室
#        周报交叉上报时产生的重复数据干扰统计
# --------------------------------------------------------------------
DEDUP_KEYS: list = ['企业名称', '排查日期']

# --------------------------------------------------------------------
#  3.4 空白字段填充值
# --------------------------------------------------------------------
#  所有空值（NaN / None / '' / '无' / '暂无'）统一填充为此字符串
#  填充后不阻塞统计，同时便于人工在 Excel 中搜索定位
#  在输出报表中，此值的单元格会以橙色加粗字体自动标注
# --------------------------------------------------------------------
FILL_VALUE: str = '待补充'

# ======================================================================
#  4. 地域前缀配置
# ======================================================================
#  用于地址自适应补全功能（complete_address 函数）
#
#  工作机制：
#    1. 检查原始地址是否已包含完整前缀 → 已包含则跳过
#    2. 否则按 district → city → province 顺序逐级检查并补全
#    3. 补全后的地址用于后续的区域统计分组
#
#  配置方法（以 XX 省 YY 市 ZZ 区为例）：
#    REGION_PREFIX = {
#        'province':  'XX省',
#        'city':      'YY市',
#        'district':  'ZZ区',
#    }
#
#  注意：修改后需重启 Flask 服务才能生效
# --------------------------------------------------------------------
REGION_PREFIX: dict = {
    'province': '',   # 省级前缀，如 'XX省'（留空则不补全）
    'city':     '',   # 市级前缀，如 'XX市'（留空则不补全）
    'district': '',   # 区县级前缀，如 'XX区' 或 'XX县'（留空则不补全）
}

